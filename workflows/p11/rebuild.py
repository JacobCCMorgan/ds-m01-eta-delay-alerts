def require(condition, message):
    if not condition:
        raise ValueError(message)


def now():
    return datetime.now(timezone.utc).isoformat()


def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('x', encoding='utf-8') as stream:
        json.dump(value, stream, sort_keys=True, indent=2, allow_nan=False)
        stream.write('\n')


def directory_bytes(directory):
    """Actual regular-file logical/allocated sizes at the measurement instant."""
    directory = Path(directory)
    logical = allocated = count = 0
    if not directory.exists():
        return {'files': 0, 'logical_bytes': 0, 'allocated_bytes': 0}
    require(not directory.is_symlink(), 'Measured directory must not be a symlink')
    for path in directory.rglob('*'):
        require(not path.is_symlink(), 'Generated output contains a symlink: ' + str(path))
        if path.is_file():
            stat = path.stat()
            logical += stat.st_size
            allocated += getattr(stat, 'st_blocks', 0) * 512
            count += 1
    return {'files': count, 'logical_bytes': logical, 'allocated_bytes': allocated}


def _verify_gzip(path, expected_sha256, expected_bytes):
    digest = hashlib.sha256()
    length = 0
    with gzip.open(path, 'rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(chunk)
            length += len(chunk)
    require(length == expected_bytes and digest.hexdigest() == expected_sha256,
            'Compressed source does not restore the exact original bytes: ' + str(path))


def _archive_owned_source(source, run_root, owner_nonce, expected_sha256):
    """Retain every generated JSONL byte in verified gzip after a successful run.

    No plain stream is removed until ALL archives have been fully decoded and
    verified. Failed compression leaves every plain input. An interruption
    during final cleanup can leave some plain inputs alongside the complete
    verified archive set. Only this worker's newly owned source is accepted.
    """
    source, run_root = Path(source).resolve(), Path(run_root).resolve()
    require(source == run_root / 'source' and not source.is_relative_to(_CHECKOUT),
            'Source archiving is restricted to the owned external worker source')
    owner_path = run_root / 'source_owner.json'
    require(owner_path.is_file() and not owner_path.is_symlink(), 'Missing worker source ownership record')
    require(json.loads(owner_path.read_text()) == {'source': 'source', 'nonce': owner_nonce},
            'Worker source ownership record differs')
    allowed = EXPECTED_INPUT_PATHS | {'validation/latent_truth.jsonl'}
    paths = {}
    for path in source.rglob('*'):
        require(not path.is_symlink(), 'Owned source must not contain links')
        if path.is_file() and path.suffix == '.jsonl':
            paths[path.relative_to(source).as_posix()] = path
    require(set(paths) == allowed and set(expected_sha256) == allowed,
            'Owned source archive inventory must contain the 20 data streams and generated truth stream')
    started = time.perf_counter()
    records = {}
    for name, path in sorted(paths.items()):
        archive = path.with_name(path.name + '.gz')
        pending = path.with_name('.' + path.name + '.gzip.tmp')
        require(not archive.exists() and not archive.is_symlink(), 'Source archive already exists')
        stat_before = path.stat()
        digest = hashlib.sha256()
        size = rows = 0
        print('ARCHIVE owned generated stream: ' + name, file=sys.stderr, flush=True)
        with pending.open('xb') as raw:
            with gzip.GzipFile(filename='', mode='wb', compresslevel=1, fileobj=raw, mtime=0) as compressed:
                with path.open('rb') as incoming:
                    for chunk in iter(lambda: incoming.read(1024 * 1024), b''):
                        digest.update(chunk)
                        size += len(chunk)
                        rows += chunk.count(b'\n')
                        compressed.write(chunk)
            raw.flush()
            os.fsync(raw.fileno())
        stat_after = path.stat()
        require((stat_before.st_ino, stat_before.st_size, stat_before.st_mtime_ns) ==
                (stat_after.st_ino, stat_after.st_size, stat_after.st_mtime_ns),
                'Generated source changed during archiving: ' + name)
        require(digest.hexdigest() == expected_sha256[name], 'Generated source SHA changed before archiving: ' + name)
        _verify_gzip(pending, expected_sha256[name], size)
        # An exclusive same-filesystem hard-link install cannot overwrite an
        # existing archive; removing its temporary name leaves one durable file.
        os.link(pending, archive)
        pending.unlink()
        records[name] = {'original_sha256': digest.hexdigest(), 'original_bytes': size,
                         'original_rows': rows, 'archive_path': archive.relative_to(source).as_posix(),
                         'archive_sha256': digest_file(archive), 'archive_bytes': archive.stat().st_size,
                         'full_decode_byte_identity_verified': True}
    for parent in {path.parent for path in paths.values()}:
        fd = os.open(parent, os.O_RDONLY)
        try:
            os.fsync(fd)
        finally:
            os.close(fd)
    result = {'status': 'passed_lossless_owned_source_archive', 'format': 'gzip',
              'compression_level': 1, 'gzip_mtime': 0, 'files': records,
              'original_bytes': sum(v['original_bytes'] for v in records.values()),
              'archive_bytes': sum(v['archive_bytes'] for v in records.values()),
              'all_archives_verified_before_any_plain_stream_removed': True,
              'archive_wall_seconds': round(time.perf_counter() - started, 6),
              'restoration': 'Decode each archive_path to its corresponding original relative path; require original_sha256 and original_bytes before use.'}
    pending_index = source / 'jsonl_archive.pending.json'
    write_json(pending_index, result)
    for path in paths.values():
        path.unlink()
    os.replace(pending_index, source / 'jsonl_archive.json')
    for parent in {source} | {path.parent for path in paths.values()}:
        fd = os.open(parent, os.O_RDONLY)
        try:
            os.fsync(fd)
        finally:
            os.close(fd)
    return result


def check_historical_files(repo, source):
    """Require every raw and processed stream to match the independent M2 oracle."""
    repo, source = Path(repo), Path(source)
    receipt_path = repo / 'reports/rebuild_report.json'
    historical = json.loads(receipt_path.read_text())
    require(historical.get('status') == 'passed', 'Historical M2 rebuild is not a pass')
    entries = historical.get('files', [])
    names = [item['path'] for item in entries]
    require(len(names) == len(set(names)), 'Historical rebuild contains duplicate paths')
    expected = {item['path']: item for item in entries if item['path'] in EXPECTED_INPUT_PATHS}
    require(set(expected) == EXPECTED_INPUT_PATHS,
            'Historical rebuild must contain all 13 raw and 7 processed files')
    actual_paths = {
        path.relative_to(source).as_posix()
        for folder in ('raw', 'processed')
        for path in (source / 'data' / folder).glob('*.jsonl')
    }
    require(actual_paths == EXPECTED_INPUT_PATHS, 'Fresh raw/processed inventory differs')
    comparisons = {}
    for name in sorted(EXPECTED_INPUT_PATHS):
        item = expected[name]
        require(item.get('equal') is True
                and item.get('original_sha256') == item.get('rebuilt_sha256'),
                'Historical oracle did not establish exact equality: ' + name)
        actual = digest_file(source / name)
        require(actual == item['original_sha256'], 'Historical raw/processed bytes differ: ' + name)
        comparisons[name] = actual
    return {'status': 'passed', 'historical_receipt_sha256': digest_file(receipt_path),
            'raw_files_compared': 13, 'processed_files_compared': 7,
            'byte_exact_sha256': comparisons,
            'parquet_scope': 'Compared as complete typed logical relations; historical Parquet bytes are not a portability requirement.'}


def warehouse_builder(source, config, *, fault=None):
    """Adapt the frozen materializer to a never-visible staging generation.

    The frozen function writes only into this run's fresh source directory.
    Its outputs become visible solely through the P11 publisher's reference.
    """
    source = Path(source)

    def builder(stage):
        stage = Path(stage)
        (source / 'sql').mkdir(exist_ok=True)
        report = build_warehouse(source, config)
        require(report.get('passed') is True and len(report.get('checks', [])) == 27
                and all(item.get('passed') is True for item in report['checks']),
                'Frozen M2 warehouse checks failed or changed population')
        required = set(config['required_tables'])
        require(len(required) == 28 and set(report['counts']) == required,
                'Full M2 warehouse must materialize exactly 28 canonical schemas')
        require(report['active_canonical_tables'] == 17 and len(report['reserved_empty_tables']) == 11,
                'Full M2 active/reserved table boundary changed')
        require(all(report['counts'][name] == 0 for name in report['reserved_empty_tables']),
                'Reserved M2 contracts unexpectedly contain rows')
        database = source / 'data' / config['database_filename']
        require(database.is_file(), 'Frozen warehouse did not create its database')
        shutil.move(str(database), stage / 'warehouse.duckdb')
        if fault:
            fault('after_database')
        parquet = stage / 'parquet'
        parquet.mkdir()
        emitted = sorted((source / 'data/parquet').glob('*.parquet'))
        require({p.stem for p in emitted} == required, 'Parquet inventory differs from required tables')
        for index, path in enumerate(emitted):
            shutil.move(str(path), parquet / path.name)
            if index == 0 and fault:
                fault('after_first_parquet')
        return {'status': 'passed_frozen_m2_materialization', 'warehouse': report,
                'scope': SCOPE, 'source_pipeline_changed': False,
                'connection_resource_settings': {'memory_limit': '2GB', 'threads': 1,
                                                  'max_temp_directory_size': '16GB',
                                                  'spill_scope': 'private generated source directory'},
                'historical_row_order_or_precision_changed': False}

    return builder


def compare_runs(first, second):
    require(first['historical_oracle']['byte_exact_sha256'] ==
            second['historical_oracle']['byte_exact_sha256'], 'Independent raw/processed runs differ')
    require(first['generated_counts'] == second['generated_counts'], 'Independent source populations differ')
    require(first['warehouse_counts'] == second['warehouse_counts'], 'Independent warehouse populations differ')
    left, right = first['tables'], second['tables']
    require(len(left) == len(right) == 28 and set(left) == set(right), 'Repeat table inventory differs')
    for name in sorted(left):
        require(left[name] == right[name], 'Repeat table schema, count or logical digest differs: ' + name)
    return {'status': 'passed', 'raw_files_compared': 13, 'processed_files_compared': 7,
            'canonical_relations_compared': 28, 'logical_rows_compared': sum(t['row_count'] for t in left.values()),
            'schema_count_and_all_row_digests_equal': True,
            'database_or_parquet_physical_byte_identity_required': False}


def _full_worker(repo, run_root, store_root, expected_current):
    from workflows.p11.publication import publish

    repo, run_root, store_root = map(lambda p: Path(p).resolve(), (repo, run_root, store_root))
    require(repo == _CHECKOUT, 'Rebuild worker must execute from the requested checkout')
    require(not run_root.exists(), 'Rebuild worker requires a fresh run directory')
    require(not run_root.is_relative_to(repo) and not repo.is_relative_to(run_root),
            'Full rebuild output must be outside the repository')
    started, clock = now(), time.perf_counter()
    before = resource.getrusage(resource.RUSAGE_SELF)
    config_path = repo / 'config/m2.json'
    config = json.loads(config_path.read_text())
    require(config.get('sample_size') == 1800 and len(config.get('required_tables', [])) == 28,
            'Full rebuild requires the original 1,800-trip / 28-schema M2 configuration')
    run_root.mkdir(parents=True)
    owner_nonce = secrets.token_hex(16)
    write_json(run_root / 'source_owner.json', {'source': 'source', 'nonce': owner_nonce})
    source = run_root / 'source'
    try:
        counts = generate(source, config)
        require(counts.get('eta_trip') == 1800 and counts.get('telemetry_event') == 197303,
                'Full frozen source population differs')
        write_source_manifest(source, counts)
        source_manifest = verify_source_manifest(source)
        (source / 'contracts').mkdir()
        shutil.copyfile(repo / 'contracts/fields.json', source / 'contracts/fields.json')
        summary = build(source, config)
        require(summary.get('snapshot_count') == 14349
                and summary.get('history_reference_count') == 2536045,
                'Full snapshot/history population differs')
        historical = check_historical_files(repo, source)
        manifest = publish(store_root, warehouse_builder(source, config),
                           expected_tables=config['required_tables'], expected_current=expected_current)
        require(verify_source_manifest(source) == source_manifest, 'Raw source changed during warehouse build')
        metadata = manifest['metadata']['warehouse']
        require(metadata['counts'].get('provenance_record') == 2775752,
                'Full provenance population differs')
        source_before_archive = directory_bytes(source)
        truth = json.loads((source / 'validation/scenario_registry.json').read_text())['publication']['files']['validation/latent_truth.jsonl']
        archive = _archive_owned_source(source, run_root, owner_nonce,
                    {**historical['byte_exact_sha256'], 'validation/latent_truth.jsonl': truth['sha256']})
        usage = resource.getrusage(resource.RUSAGE_SELF)
        rss_factor = 1 if platform.system() == 'Darwin' else 1024
        result = {
            'status': 'passed_full_frozen_m2_rebuild', 'scope': SCOPE,
            'started_at_utc': started, 'completed_at_utc': now(),
            'config_sha256': digest_file(config_path), 'generated_counts': counts,
            'historical_oracle': historical, 'generation_id': manifest['generation_id'],
            'tables': {name: {field: table[field] for field in ('row_count', 'logical_sha256', 'columns', 'comparison_order')}
                       for name, table in manifest['tables'].items()},
            'warehouse_runtime_settings': manifest['metadata']['connection_resource_settings'],
            'comparison_runtime_settings': manifest['comparison_runtime'],
            'warehouse_counts': metadata['counts'], 'warehouse_checks': metadata['checks'],
            'materialized_schemas': 28, 'populated_data_tables': 17,
            'typed_empty_tables': sorted(metadata['reserved_empty_tables']),
            'source_manifest_sha256': digest_file(source / 'data/source_manifest.json'),
            'source_archive': archive,
            'resource_measurement': {
                'wall_seconds': round(time.perf_counter() - clock, 6),
                'process_cpu_user_seconds': round(usage.ru_utime - before.ru_utime, 6),
                'process_cpu_system_seconds': round(usage.ru_stime - before.ru_stime, 6),
                'peak_process_rss_bytes': int(usage.ru_maxrss * rss_factor),
                'peak_rss_scope': 'OS high-water mark of this fresh Python worker, including imports and all native DuckDB work; not machine-wide usage.',
                'source_files_before_archiving': source_before_archive,
                'source_files_retained': directory_bytes(source),
                'published_generation_files': directory_bytes(store_root / 'generations' / manifest['generation_id']),
                'disk_measurement_scope': 'Retained file sizes before and after successful lossless source archiving; not filesystem peak spill usage.',
                'runtime': {'python': platform.python_version(), 'system': platform.system(), 'machine': platform.machine()},
            },
            'model_refitted': False, 'new_untouched_final_test': False,
            'unified_populated_28_table_warehouse_accepted': False,
        }
        write_json(run_root / 'result.json', result)
        return result
    except BaseException as exc:
        write_json(run_root / 'failure.json', {'status': 'failed_no_success_receipt',
                   'failure_type': type(exc).__name__, 'error': str(exc), 'failed_at_utc': now()})
        raise


def run_rebuild(repo, output):
    """Run two fresh full rebuild workers and compare their retained results."""
    repo, output = Path(repo).resolve(), Path(output).resolve()
    require(repo == _CHECKOUT, 'Full rebuild code must belong to the requested checkout')
    require(not output.exists(), 'Choose a fresh rebuild output; existing evidence is retained')
    require(not output.is_relative_to(repo) and not repo.is_relative_to(output),
            'Rebuild output must be outside the checkout')
    output.mkdir(parents=True)
    started = now()
    store = output / 'store'
    results = []
    try:
        for index in range(2):
            run = output / f'run_{index + 1:02d}'
            command = [sys.executable, '-I', '-B', str(Path(__file__).resolve()), 'worker',
                       '--repo', str(repo), '--run', str(run), '--store', str(store)]
            if results:
                command.extend(['--expected-current', results[-1]['generation_id']])
            log = output / f'run_{index + 1:02d}.log'
            print(f'RUN full rebuild {index + 1}/2; log: {log}', file=sys.stderr, flush=True)
            with log.open('x', encoding='utf-8') as stream:
                subprocess.run(command, check=True, cwd=repo, stdout=stream,
                               stderr=subprocess.STDOUT, text=True)
            result = json.loads((run / 'result.json').read_text())
            require(result.get('status') == 'passed_full_frozen_m2_rebuild', 'Worker did not finish a full rebuild')
            results.append(result)
        repeat = compare_runs(*results)
        receipt = {'status': 'passed_two_full_frozen_m2_rebuilds', 'scope': SCOPE,
                   'started_at_utc': started, 'completed_at_utc': now(), 'runs': results,
                   'repeatability': repeat, 'retained_external_bytes': directory_bytes(output),
                   'resources_are_observed_not_acceptance_thresholds': True,
                   'ci_executed': False, 'quality_accepted': False, 'operational_approval': False}
        write_json(output / 'rebuild.json', receipt)
        return receipt
    except BaseException as exc:
        write_json(output / 'failure.json', {'status': 'failed_no_success_receipt',
                   'failure_type': type(exc).__name__, 'error': str(exc), 'failed_at_utc': now(),
                   'completed_runs': len(results)})
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['worker'])
    parser.add_argument('--repo', type=Path, required=True)
    parser.add_argument('--run', type=Path, required=True)
    parser.add_argument('--store', type=Path, required=True)
    parser.add_argument('--expected-current')
    args = parser.parse_args()
    result = _full_worker(args.repo, args.run, args.store, args.expected_current)
    print(json.dumps({'status': result['status'], 'generation_id': result['generation_id']}, sort_keys=True))


if __name__ == '__main__':
    main()
